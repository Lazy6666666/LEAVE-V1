export const documentStats: DocumentStats = {
  totalDocuments: mockDocuments.length,
  requiredDocuments: mockDocuments.filter((doc) => doc.isRequired).length,
  expiringSoon: mockDocuments.filter((doc) => {
    if (!doc.expiryDate) return false;
    const daysUntilExpiry = Math.ceil(
      (doc.expiryDate.getTime() - new Date().getTime()) / (1000 * 60 * 60 * 24)
    );
    return daysUntilExpiry > 0 && daysUntilExpiry <= 30;
  }).length,
  expired: mockDocuments.filter(
    (doc) => doc.expiryDate && doc.expiryDate < new Date()
  ).length,
  categoriesCount: documentCategories.length,
  totalSize: mockDocuments.reduce((total, doc) => total + doc.fileSize, 0),
};
